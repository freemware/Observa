// ── Live refresh overlay (v0.11.0, opt-in — see background/list-refresh.js) ──
// The bundled `T` above is a dated snapshot and never changes at runtime.
// When the user has opted into list refresh, a freshly-fetched copy of the
// same Disconnect list (same source, same {domain: [org, category]} shape)
// is loaded from chrome.storage.local into `_live` and checked FIRST; `T`
// is always the fallback, so a failed/never-attempted refresh degrades to
// exactly today's behavior, never to no classification at all.
let _live = null;

/** Called once at service-worker startup, and again after a successful
 * refresh, so new data takes effect without waiting for a worker restart. */
export async function loadLiveTrackerOverlay() {
  try {
    const stored = await chrome.storage.local.get('observa:liveTrackerList');
    _live = stored['observa:liveTrackerList'] ?? null;
  } catch { _live = null; }
}

function _entryFor(domain) {
  return (_live && _live[domain]) ?? T[domain];
}

/**
 * Look up a domain in the tracker list.
 * @param {string} domain
 * @returns {{ organization: string, category: string, provenance: 'Classified' } | null}
 */
export function lookupTracker(domain) {
  const e = _entryFor(domain);
  if (!e) return null;
  return { organization: e[0], category: e[1], provenance: 'Classified' };
}

/** @param {string} domain @returns {boolean} */
export function isKnownTracker(domain) {
  return !!_entryFor(domain);
}

